-- AMJAD PROGRAMS: schema + secure single-admin access
create table if not exists public.admin_users (
 user_id uuid primary key references auth.users(id) on delete cascade,
 created_at timestamptz not null default now()
);
create table if not exists public.site_items (
 id bigint generated by default as identity primary key,
 item_type text not null default 'program' check(item_type in ('program','link')),
 title text not null,
 description text not null default '',
 item_url text not null,
 image_url text not null default '',
 category text not null default 'essential',
 icon text not null default '📦',
 is_published boolean not null default true,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create index if not exists site_items_published_created_idx on public.site_items(is_published,created_at desc);
alter table public.admin_users enable row level security;
alter table public.site_items enable row level security;

create or replace function public.amjad_is_admin()
returns boolean language sql stable security definer set search_path=''
as $$
 select exists(select 1 from public.admin_users where user_id=(select auth.uid()));
$$;
revoke all on function public.amjad_is_admin() from public;
grant execute on function public.amjad_is_admin() to anon, authenticated;

drop policy if exists "Admins read own record" on public.admin_users;
create policy "Admins read own record" on public.admin_users
for select to authenticated using(user_id=(select auth.uid()));

drop policy if exists "Public read published items" on public.site_items;
create policy "Public read published items" on public.site_items
for select to anon,authenticated using(is_published=true or public.amjad_is_admin());

drop policy if exists "Admin insert items" on public.site_items;
create policy "Admin insert items" on public.site_items
for insert to authenticated with check(public.amjad_is_admin());

drop policy if exists "Admin update items" on public.site_items;
create policy "Admin update items" on public.site_items
for update to authenticated using(public.amjad_is_admin()) with check(public.amjad_is_admin());

drop policy if exists "Admin delete items" on public.site_items;
create policy "Admin delete items" on public.site_items
for delete to authenticated using(public.amjad_is_admin());

grant select on public.site_items to anon,authenticated;
grant insert,update,delete on public.site_items to authenticated;
grant select on public.admin_users to authenticated;
grant usage,select on sequence public.site_items_id_seq to authenticated;

